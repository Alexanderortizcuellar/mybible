/// Find standard book metadata by its number.
pub fn find_book_by_number(book_number: impl Into<BookNumber>) -> Option<&'static BookInfo> {
    let num = book_number.into();
    ALL_BOOKS.iter().find(|b| b.book_number == num)
}

/// Find standard book metadata by English or Russian abbreviation or title (case-insensitive).
pub fn find_book_by_name(name: &str) -> Option<&'static BookInfo> {
    let name = name.trim();
    ALL_BOOKS.iter().find(|b| {
        b.short_name_eng.eq_ignore_ascii_case(name)
            || b.long_name_eng.eq_ignore_ascii_case(name)
            || b.short_name_rus.eq_ignore_ascii_case(name)
            || b.long_name_rus.eq_ignore_ascii_case(name)
    })
}
